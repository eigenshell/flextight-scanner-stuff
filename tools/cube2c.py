"""Compile .cube 3D tables into C for the lut3d print module (libft/ft_pm.h).

    python3 tools/cube2c.py <dir with .cube files> <out.h>

Each <name>.cube becomes `static const ft_cube CUBE_<name>` (the name in
lower case, anything but a-z0-9 as '_'), for an emulsion entry in
libft/ft_emulsion.c to use. Accepts LUT_3D_SIZE 2..33, the 0..1 domain and
values in 0..1 (sRGB-encoded); the header is the same bytes for the same
files, so it can be committed and checked (tests/test_print.py).
"""
import re
import sys
from pathlib import Path

MAX_N = 33


def fail(path, line, msg):
    sys.exit("cube2c: %s:%d: %s" % (path.name, line, msg))


def read_cube(path):
    n = None
    title = ""
    rows = []
    for ln, raw in enumerate(path.read_text().splitlines(), 1):
        s = raw.split("#", 1)[0].strip()
        if not s:
            continue
        word = s.split()[0]
        if word == "TITLE":
            title = s[5:].strip().strip('"')
        elif word == "LUT_3D_SIZE":
            try:
                n = int(s.split()[1])
            except (IndexError, ValueError):
                fail(path, ln, "LUT_3D_SIZE needs a number")
            if not 2 <= n <= MAX_N:
                fail(path, ln, "LUT_3D_SIZE %d (2..%d)" % (n, MAX_N))
        elif word in ("DOMAIN_MIN", "DOMAIN_MAX"):
            want = [0.0] * 3 if word == "DOMAIN_MIN" else [1.0] * 3
            try:
                got = [float(v) for v in s.split()[1:]]
            except ValueError:
                got = None
            if got != want:
                fail(path, ln, "%s must be %s" % (
                    word, " ".join("%g" % v for v in want)))
        elif re.match(r"^[A-Z_0-9]+$", word) and not re.match(r"^[0-9]", word):
            fail(path, ln, "%s is not supported" % word)
        else:
            try:
                v = [float(x) for x in s.split()]
            except ValueError:
                fail(path, ln, "not three numbers")
            if len(v) != 3:
                fail(path, ln, "not three numbers")
            if not all(0 <= x <= 1 for x in v):
                fail(path, ln, "values are 0..1 (sRGB-encoded)")
            rows.append(v)
    if n is None:
        fail(path, 0, "no LUT_3D_SIZE")
    if len(rows) != n ** 3:
        fail(path, 0, "%d rows, LUT_3D_SIZE %d needs %d" % (
            len(rows), n, n ** 3))
    return n, title, rows


def cfloat(x):
    """x as a C float literal: "0.5f", "1.0f" (never the invalid "1f")"""
    s = "%.9g" % x
    if not any(ch in s for ch in ".e"):
        s += ".0"
    return s + "f"


def cname(path):
    name = re.sub(r"[^a-z0-9]", "_", path.stem.lower())
    if not name[:1].isalpha():
        sys.exit("cube2c: %s: the name must start with a letter" % path.name)
    return name


def main(argv):
    if len(argv) != 3:
        sys.exit("usage: cube2c.py <dir> <out.h>")
    src, out = Path(argv[1]), Path(argv[2])
    text = [
        "/* SPDX-License-Identifier: GPL-2.0-or-later */",
        "/* Generated by tools/cube2c.py from the .cube files in "
        "libft/emulsions/",
        " * (make luts):",
        " * do not edit. Included by ft_emulsion.c only. */",
        "#ifndef FT_EMULSION_LUTS_H",
        "#define FT_EMULSION_LUTS_H",
        '#include "ft_print.h"',
    ]
    for path in sorted(src.glob("*.cube")):
        n, title, rows = read_cube(path)
        name = cname(path)
        text.append("")
        text.append("/* %s: %s%d^3 */" % (
            path.name, ('"%s", ' % title) if title else "", n))
        text.append("static const float CUBE_%s_RGB[] = {" % name)
        for v in rows:
            text.append("    %s," % ", ".join(cfloat(x) for x in v))
        text.append("};")
        text.append("static const ft_cube CUBE_%s = { %d, CUBE_%s_RGB };" % (
            name, n, name))
    text.append("")
    text.append("#endif")
    out.write_text("\n".join(text) + "\n")


if __name__ == "__main__":
    main(sys.argv)
